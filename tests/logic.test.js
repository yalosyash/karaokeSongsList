import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { SONGS, queryMatcher } from "../src/catalog/catalog.js";
import { cleanLines } from "../scripts/lib/lyrics.js";
import { norm, searchNorm, escapeHtml } from "../src/core/text.js";
import {
  versionsOf,
  isVideoBlocked,
  isBlocked,
} from "../src/features/player/youtube.js";

test("generated catalog preserves all source songs and metadata", async () => {
  const source = JSON.parse(
    await fs.readFile(
      new URL("../content/songs.json", import.meta.url),
      "utf8",
    ),
  );
  const fields = ["id", "artist", "title", "genre", "category", "lang"];
  assert.deepEqual(
    SONGS.map((s) => fields.map((f) => s[f])),
    source.map((s) => fields.map((f) => s[f])),
  );
  assert.equal(
    new Set(SONGS.map((s) => s.id)).size,
    SONGS.length,
    "duplicate song IDs",
  );
});

test("normalization: mixed alphabets, case, ё and punctuation have literal expected results", () => {
  assert.equal(norm("  Ёж — РОК!  "), "еж рок");
  assert.equal(searchNorm("МакSим"), "максим");
  assert.equal(escapeHtml("<script>\"&'"), "&lt;script&gt;&quot;&amp;&#39;");
});

// These inputs and expected booleans are handwritten, not generated by the
// search implementation or read from the rendered result.
const searchSong = {
  search: "макsим знаешь ли ты поп",
  searchAlt: "максим знаешь ли ты поп",
};
for (const [query, expected] of [
  ["максим", true],
  ["МАКSИМ", true],
  ["ты знаешь", true],
  ["поп", true],
  ["земфира", false],
  ["знаешь рок", false],
  ["", true],
]) {
  test(`search contract: ${JSON.stringify(query)}`, () =>
    assert.equal(queryMatcher(query)(searchSong), expected));
}

test("lyrics cleanup removes markup and duplicates without losing words", () => {
  assert.deepEqual(
    cleanLines(
      "[Verse 1]\n[00:02.30]Ёлка &amp; дом\nЁлка &amp; дом\n&#x2028;Кабан — чуток желудей\n(х2)",
    ),
    ["Ёлка & дом", "Кабан — чуток желудей"],
  );
  assert.equal(cleanLines("[Chorus]\n...\n"), null);
});

test("three video versions and mixed availability retain their IDs", () => {
  const song = {
    id: "primary",
    alt: ["blocked-alt", "working-alt"],
    blocked: ["blocked-alt"],
  };
  assert.deepEqual(versionsOf(song), ["primary", "blocked-alt", "working-alt"]);
  assert.equal(isVideoBlocked(song, "blocked-alt"), true);
  assert.equal(isVideoBlocked(song, "working-alt"), false);
  assert.equal(isBlocked(song), false);
  assert.equal(isBlocked({ ...song, noembed: true }), true);
});
