test("embed checker waits for playback or an error after CUED", async () => {
  const script = await fs.readFile(
    new URL("../scripts/embed-check/embed-check.js", import.meta.url),
    "utf8",
  );
  const players = new Map();
  const timers = new Set();
  const window = {};
  const PlayerState = { PLAYING: 1, CUED: 5 };
  runInNewContext(script, {
    window,
    location: new URL("http://localhost"),
    URLSearchParams,
    document: {
      getElementById: () => ({ appendChild() {} }),
      createElement: () => ({}),
    },
    YT: {
      PlayerState,
      Player: class {
        constructor(_holder, { videoId, events }) {
          players.set(videoId, events);
        }
      },
    },
    setTimeout(callback, delay) {
      if (delay > 0) timers.add(callback);
      return callback;
    },
    clearTimeout: (timer) => timers.delete(timer),
  });

  const checked = window.checkBatch(["plays", "blocked", "cued", "silent"]);
  for (const id of ["plays", "blocked", "cued"]) {
    players.get(id).onStateChange({ data: PlayerState.CUED });
  }
  players.get("plays").onStateChange({ data: PlayerState.PLAYING });
  players.get("blocked").onError({ data: 150 });
  for (const expire of timers) expire();

  const results = await checked;
  assert.equal(results.plays.status, "ok");
  assert.equal(results.blocked.status, "error");
  assert.equal(results.blocked.error, 150);
  assert.equal(results.cued.status, "cued");
  assert.equal(results.silent.status, "silent");
});

test("embed reports keep confirmed results and only block errors 101 and 150", () => {
  const previous = [
    { id: "plays", status: "ok" },
    { id: "blocked", status: "error", error: 150 },
    { id: "recovered", status: "error", error: 150 },
    { id: "restricted", status: "ok" },
    { id: "unchecked", status: "ok" },
  ];
  const results = [
    { id: "plays", status: "silent" },
    { id: "blocked", status: "cued" },
    { id: "recovered", status: "ok" },
    { id: "restricted", status: "error", error: 101 },
    { id: "new-cued", status: "cued" },
    { id: "new-silent", status: "silent" },
    { id: "new-error", status: "error", error: 153 },
  ];
  const merged = mergeEmbedResults(previous, results);
  assert.deepEqual(merged, [
    previous[0],
    previous[1],
    results[2],
    results[3],
    previous[4],
    ...results.slice(4),
  ]);
  assert.deepEqual(
    merged.filter(isEmbedBlocked).map(({ id }) => id),
    ["blocked", "restricted"],
  );
});

test("generated catalog preserves all source songs and metadata", async () => {
  const source = JSON.parse(
    await fs.readFile(
      new URL("../content/songs.json", import.meta.url),
      "utf8",
    ),
  );
  const fields = ["id", "artist", "title", "genre", "category", "lang"];
  assert.deepEqual(
    SONGS.map((s) => fields.map((f) => s[f])),
    source.map((s) => fields.map((f) => s[f])),
  );
  assert.equal(
    new Set(SONGS.map((s) => s.id)).size,
    SONGS.length,
    "duplicate song IDs",
  );
});

test("generated catalog preserves every stored lyric line in order", async () => {
  const lyrics = JSON.parse(
    await fs.readFile(
      new URL("../content/lyrics.json", import.meta.url),
      "utf8",
    ),
  );
  for (const song of SONGS) {
    for (const section of ["verse", "chorus"]) {
      const lines = lyrics[song.id]?.[section];
      assert.deepEqual(
        song[section],
        lines?.length ? lines : null,
        `${song.id} ${section}`,
      );
    }
  }
});

test("normalization: mixed alphabets, case, ё and punctuation have literal expected results", () => {
  assert.equal(norm("  Ёж — РОК!  "), "еж рок");
  assert.equal(searchNorm("МакSим"), "максим");
  assert.equal(escapeHtml("<script>\"&'"), "&lt;script&gt;&quot;&amp;&#39;");
});

// These inputs and expected booleans are handwritten, not generated by the
// search implementation or read from the rendered result.
const searchSong = {
  search: "макsим знаешь ли ты поп",
  searchAlt: "максим знаешь ли ты поп",
};
for (const [query, expected] of [
  ["максим", true],
  ["МАКSИМ", true],
  ["ты знаешь", true],
  ["поп", true],
  ["земфира", false],
  ["знаешь рок", false],
  ["", true],
]) {
  test(`search contract: ${JSON.stringify(query)}`, () =>
    assert.equal(queryMatcher(query)(searchSong), expected));
}

test("lyrics require the first sections and keep lines after annotations", () => {
  assert.equal(buildLyrics("[Verse 10]\nLater verse\n[Chorus]\nHook"), null);
  assert.deepEqual(
    buildLyrics(
      "[Verse 2a]\nLater verse\n[Verse 1: Artist]\nLine &amp; line\n[spoken]\nLine &amp; line\nHook:\nOther section\n[Chorus]\nFirst line\nSecond line",
    ),
    {
      verse: ["Line & line", "Line & line"],
      chorus: ["First line", "Second line"],
    },
  );
});

test("lyrics require manual review for unknown boundaries and repeat markers", () => {
  assert.equal(
    buildLyrics(
      "Verse 1:\nVerse line\nRefrain:\nRefrain line\nChorus:\nChorus line",
    ),
    null,
  );
  assert.equal(
    buildLyrics(
      "Verse 1:\nVerse line\nRefrain: Soloist\nRefrain line\nChorus:\nChorus line",
    ),
    null,
  );
  assert.equal(
    buildLyrics(
      "[Verse 1]\nVerse line\n[Refrain]\nRefrain line\n[Chorus]\nChorus line",
    ),
    null,
  );
  assert.equal(
    buildLyrics("[Verse 1]\nVerse line\n[Chorus]\nChorus line\n(x2)"),
    null,
  );
  assert.equal(
    buildLyrics("[Verse 1]\nVerse line\n[Chorus]\nChorus line (x2)"),
    null,
  );
  assert.equal(buildLyrics("[Verse 1]\nVerse line\n[Chorus]\n..."), null);
});

test("lyrics stop collecting at an attributed bridge heading", () => {
  assert.deepEqual(
    buildLyrics(
      "[Verse 1]\nVerse line\nBridge: Soloist\nBridge line\n[Chorus]\nChorus line",
    ),
    { verse: ["Verse line"], chorus: ["Chorus line"] },
  );
});

test("three video versions and mixed availability retain their IDs", () => {
  const song = {
    id: "primary",
    alt: ["blocked-alt", "working-alt"],
    blocked: ["blocked-alt"],
  };
  assert.deepEqual(versionsOf(song), ["primary", "blocked-alt", "working-alt"]);
  assert.equal(isVideoBlocked(song, "blocked-alt"), true);
  assert.equal(isVideoBlocked(song, "working-alt"), false);
  assert.equal(isBlocked(song), false);
  assert.equal(isBlocked({ ...song, noembed: true }), true);
});
